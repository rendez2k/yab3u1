assert.equal(cfg.enable_support,'1');
assert.match(cfg.printer_settings_id,/SLICE ONLY/);
assert.equal(parsed.sourceSettings.layer_height,'0.24');
const normal=convertProject(parsed,parsed.plates[0].id,null,{target:'snapmaker'});
assert.doesNotMatch(dec.decode(normal.entries.get(SRC_BBL_PROJECT)),/SLICE ONLY|YAB3D_VIRTUAL_SLICE_ONLY/);
console.log('slice-only preparation: virtual tools, process overrides and normal export isolation passed');
